// package.json is authoritative; dependent npm manifests are synchronized here.
import { readFile, writeFile } from 'node:fs/promises';
const version = process.argv[2];
if (!/^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)$/.test(version ?? ''))
	throw new Error('Expected Y.M.P');
for (const file of ['package.json', 'frontend/package.json']) {
	const data = JSON.parse(await readFile(new URL(`../${file}`, import.meta.url), 'utf8'));
	data.version = version;
	await writeFile(new URL(`../${file}`, import.meta.url), JSON.stringify(data, null, '\t') + '\n');
}
await writeFile(
	new URL('../backend/internal/buildinfo/version.go', import.meta.url),
	`// Code generated by scripts/set-version.mjs; DO NOT EDIT.\npackage buildinfo\n\nvar Version = "${version}"\n`
);
